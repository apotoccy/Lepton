PREAMBLE_HEAD = r'''/* Generated by leptonc. Do not edit by hand. */
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

#if defined(__GNUC__) || defined(__clang__)
#  define LP_UNUSED __attribute__((unused))
#else
#  define LP_UNUSED
#endif

/* f16: native _Float16 when the compiler provides it, else a label over
   float. The fallback is not true half-precision; it exists so programs
   compile on older toolchains while numeric work lands in stages. */
#if defined(__FLT16_MANT_DIG__)
typedef _Float16 lp_f16;
#else
typedef float    lp_f16;
#endif

/* bf16: native __bf16 when available, else a 16-bit container holding the
   top half of an f32. The fallback conversion is a shift and a union
   reinterpret, which is what makes bf16 cheap on hardware without native
   support. Rounding is truncation; round-to-nearest-even is a follow-up. */
#if defined(__BFLT16_MANT_DIG__)
typedef __bf16 lp_bf16;
static inline float   lp_bf16_to_f32  (lp_bf16 x) { return (float)x; }
static inline lp_bf16 lp_bf16_from_f32(float   x) { return (lp_bf16)x; }
#else
typedef uint16_t lp_bf16;
typedef union { float f; uint32_t u; } lp_bf16_bits;
static inline float lp_bf16_to_f32(lp_bf16 x) {
    lp_bf16_bits b;
    b.u = ((uint32_t)x) << 16;
    return b.f;
}
static inline lp_bf16 lp_bf16_from_f32(float x) {
    lp_bf16_bits b;
    b.f = x;
    return (lp_bf16)(b.u >> 16);
}
#endif

/* Fixed-point types. Each is a signed integer holding `raw / 2^FRAC` of
   the real value. Arithmetic widens to a larger integer, applies
   saturation, and narrows back. This is the representation used by
   quantized inference on hardware without an FPU. */
#define LP_QDEFINE(NAME, TYPE, WIDE, FRAC)                                    \
  typedef TYPE lp_##NAME;                                                     \
  static inline float lp_##NAME##_to_f32(lp_##NAME x) {                       \
    return (float)x / (float)((WIDE)1 << (FRAC));                             \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_from_f32(float x) {                     \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (x >= 1.0f) return (lp_##NAME)maxv;                                    \
    if (x <= -1.0f) return (lp_##NAME)minv;                                   \
    float scaled = x * (float)((WIDE)1 << (FRAC));                            \
    WIDE v = (WIDE)(scaled + (scaled >= 0.0f ? 0.5f : -0.5f));                \
    if (v > maxv) return (lp_##NAME)maxv;                                     \
    if (v < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)v;                                                      \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_add(lp_##NAME a, lp_##NAME b) {         \
    WIDE s = (WIDE)a + (WIDE)b;                                               \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (s > maxv) return (lp_##NAME)maxv;                                     \
    if (s < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)s;                                                      \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_sub(lp_##NAME a, lp_##NAME b) {         \
    WIDE s = (WIDE)a - (WIDE)b;                                               \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (s > maxv) return (lp_##NAME)maxv;                                     \
    if (s < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)s;                                                      \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_mul(lp_##NAME a, lp_##NAME b) {         \
    WIDE p = (WIDE)a * (WIDE)b;                                               \
    p += (WIDE)1 << (FRAC - 1);                                               \
    p >>= FRAC;                                                               \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (p > maxv) return (lp_##NAME)maxv;                                     \
    if (p < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)p;                                                      \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_div(lp_##NAME a, lp_##NAME b) {         \
    if (b == 0) return (lp_##NAME)(((WIDE)1 << (FRAC)) - 1);                  \
    WIDE q = ((WIDE)a << FRAC) / (WIDE)b;                                     \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (q > maxv) return (lp_##NAME)maxv;                                     \
    if (q < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)q;                                                      \
  }

LP_QDEFINE(q7,  int8_t,  int16_t,  7)
LP_QDEFINE(q15, int16_t, int32_t, 15)
LP_QDEFINE(q31, int32_t, int64_t, 31)
#undef LP_QDEFINE

/* Vector typedefs are target-specific; emitted by make_preamble(). */
'''

PREAMBLE_VEC_OPS = r'''
/* Elementwise vector arithmetic, scalar fallback. GCC/Clang at -O2 turn
   these loops into SIMD when the target supports it, so this is the
   portable baseline. Per-target intrinsics replace this later. */
#define LP_VEC_OPS(NAME, TYPE, COUNT)                                         \
  static inline TYPE lp_##NAME##_add(TYPE a, TYPE b) {                        \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = a.e[i] + b.e[i];         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_sub(TYPE a, TYPE b) {                        \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = a.e[i] - b.e[i];         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_mul(TYPE a, TYPE b) {                        \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = a.e[i] * b.e[i];         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_div(TYPE a, TYPE b) {                        \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = a.e[i] / b.e[i];         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_neg(TYPE a) {                                \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = -a.e[i];                 \
    return r;                                                                 \
  }

LP_VEC_OPS(v2f64, lp_v2f64,  2)
LP_VEC_OPS(v4f32, lp_v4f32,  4)
LP_VEC_OPS(v4i32, lp_v4i32,  4)
LP_VEC_OPS(v8i16, lp_v8i16,  8)
LP_VEC_OPS(v16i8, lp_v16i8, 16)
#undef LP_VEC_OPS
'''

RUNTIME = r'''
/* ---------------------------------------------------------------------------
   Lepton host runtime.  Everything here is replaceable: for a bare-metal
   target you supply your own lp_print / lp_cat / lp_alloc and compile with
   --freestanding (no runtime emitted at all).
   --------------------------------------------------------------------------- */
typedef unsigned long lp_size;

extern long write(int, const void *, lp_size);
extern void *malloc(lp_size);
extern void  free(void *);
extern int   snprintf(char *, lp_size, const char *, ...);
extern void  exit(int);

static LP_UNUSED void lp_puts_raw(const char *s) {
    lp_size n = 0;
    while (s[n]) n++;
    (void)write(1, s, n);
}
static LP_UNUSED char *lp_alloc(lp_size n) {
    char *p = (char *)malloc(n);
    if (!p) {
        const char *m = "lepton: out of memory\n";
        (void)write(2, m, 22);
        exit(1);
    }
    return p;
}
static LP_UNUSED const char *lp_cat(const char *a, const char *b) {
    lp_size la = 0, lb = 0, k;
    while (a[la]) la++;
    while (b[lb]) lb++;
    char *r = lp_alloc(la + lb + 1);
    for (k = 0; k < la; k++) r[k] = a[k];
    for (k = 0; k < lb; k++) r[la + k] = b[k];
    r[la + lb] = 0;
    return r;
}
static LP_UNUSED const char *lp_str_i64(int64_t v) {
    char tmp[24];
    int i = 0, j = 0, neg = v < 0;
    uint64_t u = neg ? (uint64_t)(-(v + 1)) + 1u : (uint64_t)v;
    do { tmp[i++] = (char)('0' + (int)(u % 10u)); u /= 10u; } while (u);
    char *r = lp_alloc((lp_size)i + (lp_size)neg + 1);
    if (neg) r[j++] = '-';
    while (i > 0) r[j++] = tmp[--i];
    r[j] = 0;
    return r;
}
static LP_UNUSED const char *lp_str_u64(uint64_t u) {
    char tmp[24];
    int i = 0, j = 0;
    do { tmp[i++] = (char)('0' + (int)(u % 10u)); u /= 10u; } while (u);
    char *r = lp_alloc((lp_size)i + 1);
    while (i > 0) r[j++] = tmp[--i];
    r[j] = 0;
    return r;
}
static LP_UNUSED const char *lp_str_f64(double v) {
    char *r = lp_alloc(40);
    snprintf(r, 40, "%g", v);
    return r;
}
static LP_UNUSED const char *lp_str_bool(int v) { return v ? "true" : "false"; }
static LP_UNUSED const char *lp_str_char(char c) {
    char *r = lp_alloc(2); r[0] = c; r[1] = 0; return r;
}
static LP_UNUSED void lp_print(const char *s)  { lp_puts_raw(s); }
static LP_UNUSED void lp_println(const char *s) { lp_puts_raw(s); lp_puts_raw("\n"); }
static LP_UNUSED void lp_panic(const char *s) {
    lp_puts_raw("panic: "); lp_puts_raw(s); lp_puts_raw("\n"); exit(1);
}
'''

def make_preamble(target):
    """Assemble the preamble for a given Target."""
    headers = '\n'.join(target.include_headers)
    if headers:
        headers = '\n' + headers + '\n'
    typedefs = '\n'.join(target.vector_typedefs.values())
    return PREAMBLE_HEAD + headers + '\n' + typedefs + '\n' + PREAMBLE_VEC_OPS


def c_string(s):
    """Emit a C string literal, safe for arbitrary bytes."""
    parts, cur = [], []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            cur.append('\\"')
        elif ch == '\\':
            cur.append('\\\\')
        elif ch == '\n':
            cur.append('\\n')
        elif ch == '\t':
            cur.append('\\t')
        elif ch == '\r':
            cur.append('\\r')
        elif 32 <= o < 127:
            cur.append(ch)
        else:
            cur.append('\\%03o' % o)
            parts.append(''.join(cur))
            cur = []
    parts.append(''.join(cur))
    return '"' + '" "'.join(parts) + '"'


class CEmitter:
    def __init__(self, module, fname, freestanding=False, target=None):
        from lepton_target import get_target, Target
        self.module = module
        self.fname = fname
        self.freestanding = freestanding
        if target is None:
            target = 'scalar'
        if isinstance(target, str):
            target = get_target(target)
        elif not isinstance(target, Target):
            raise TypeError(f"target must be a string or Target, "
                            f"got {type(target).__name__}")
        self.target = target
        self.out = []
        self.indent = 0

    def emit(self, line=""):
        self.out.append('    ' * self.indent + line)

    def err(self, msg):
        raise CompileError(msg, 0, 0, self.fname)

    # -- types ---------------------------------------------------------------
    def resolve(self, t):
        if t is None:
            return ('prim', 'void')
        if t[0] == 'prim':
            if t[1] in PRIMS:
                return t
            self.err(f"unknown primitive type '{t[1]}'")
        if t[0] == 'ptr':
            return ('ptr', self.resolve(t[1]))
        if t[0] == 'array':
            return ('array', self.resolve(t[1]), t[2])
        if t[0] == 'named':
            if t[1] in self.module.structs or t[1] in self.module.enums:
                return t
            self.err(f"unknown type '{t[1]}'")
        self.err(f"bad type {t!r}")

    def ctype(self, t):
        t = self.resolve(t)
        if t[0] == 'prim':
            return CTYPE[t[1]]
        if t[0] == 'ptr':
            return self.ctype(t[1]) + '*'
        if t[0] == 'array':
            return self.ctype(t[1])
        if t[0] == 'named':
            return t[1]
        self.err(f"bad type {t!r}")

    # -- top level -----------------------------------------------------------
    def compile(self):
        self.emit(make_preamble(self.target))
        if not self.freestanding:
            self.emit(RUNTIME)
        self.emit()

        for name, fields in self.module.structs.items():
            self.emit(f"typedef struct {name} {{")
            self.indent += 1
            for fname, ftype in fields:
                self.emit(f"{self.ctype(self.resolve(ftype))} {fname};")
            self.indent -= 1
            self.emit(f"}} {name};")
            self.emit()

        for name, variants in self.module.enums.items():
            self.emit("typedef enum {")
            self.indent += 1
            self.emit(", ".join(f"{name}_{v}" for v in variants))
            self.indent -= 1
            self.emit(f"}} {name};")
            self.emit()

        self.emit()   # blank line the AST emitter also emits after consts
        
        for name, (params, ret) in self.module.externs.items():
            r = self.resolve(ret) if ret else ('prim', 'void')
            ps = ", ".join(f"{self.ctype(self.resolve(p[1]))} {p[0]}"
                           for p in params)
            if not ps:
                ps = "void"
            self.emit(f"{self.ctype(r)} {name}({ps});")

        for f in self.module.funcs:
            r = self.ret_type(f)
            ps = self.param_list(f)
            self.emit(f"{self.ctype(r)} {f.cname}({ps});")
        self.emit()

        for f in self.module.funcs:
            self.emit_fn(f)

        return '\n'.join(self.out) + '\n'

    def ret_type(self, f):
        if f.name == 'main':
            return ('prim', 'i32')
        return self.resolve(f.ret) if f.ret else ('prim', 'void')

    def param_list(self, f):
        ps = ", ".join(f"{self.ctype(self.resolve(p[1]))} {p[0]}"
                       for p in f.params)
        return ps if ps else "void"

    # -- function bodies ----------------------------------------------------- 
    def emit_fn(self, f):
        r = self.ret_type(f)
        if f.name == 'main' and not f.params:
            sig = "int main(void)"
        else:
            sig = f"{self.ctype(r)} {f.cname}({self.param_list(f)})"
        self.emit(sig + " {")
        self.indent += 1

        # Hoist every named local to the top of the function. IR values are
        # function-scoped; C is block-scoped. Declaring all of them up front
        # makes a bind in one IR block visible to its siblings and to the
        # merge block, which is what the lowerer assumes.
        for kind, name, ty in self.hoisted_decls(f):
            init = self.zero_literal(ty) if kind == 'local' else ''
            if init:
                self.emit(f"{self.ctype(ty)} {name} = {init};")
            else:
                self.emit(f"{self.ctype(ty)} {name};")

        targets = self.jump_targets(f)
        for block in f.blocks:
            if block.label in targets:
                self.emit(f"lbl_{block.label}: {{")
                self.indent += 1
                for instr in block.instrs:
                    self.emit_instr(instr)
                self.indent -= 1
                self.emit("}")
            else:
                for instr in block.instrs:
                    self.emit_instr(instr)

        self.indent -= 1
        self.emit("}")
        self.emit()
        
    def hoisted_decls(self, f):
        """Every name that needs a top-of-function declaration:
        source-level IRBind names and IR temps. IR values are function-
        scoped; C is block-scoped, so all declarations are hoisted.

        Any instruction that carries a non-None `dst` gets its temp
        hoisted automatically, so new instructions need no update here.
        """
        seen_locals = set()
        seen_temps = set()
        result = []
        for block in f.blocks:
            for instr in block.instrs:
                if isinstance(instr, IRBind):
                    if instr.name not in seen_locals:
                        seen_locals.add(instr.name)
                        result.append(('local', instr.name, instr.type))
                dst = getattr(instr, 'dst', None)
                if isinstance(dst, IRTemp) and dst.id not in seen_temps:
                    seen_temps.add(dst.id)
                    result.append(('temp', f"_t{dst.id}", dst.type))
        return result
        

    def zero_literal(self, t):
        if is_vector(t):
            return '{{0}}'
        if t and t[0] == 'named':
            return '{0}'
        if t and t[0] == 'prim' and t[1] in ('q7', 'q15', 'q31'):
            return '0'
        if t == ('prim', 'bf16'):
            return '((lp_bf16)0.0f)'
        if t and t[0] == 'prim' and t[1] in ('f16', 'f32', 'f64'):
            return '0.0'
        if t == ('prim', 'bool'):
            return 'false'
        if t and t[0] == 'prim' and t[1] == 'str':
            return '""'
        return '0'
       

    def jump_targets(self, f):
        targets = set()
        for block in f.blocks:
            for instr in block.instrs:
                if isinstance(instr, IRJump):
                    targets.add(instr.target)
                elif isinstance(instr, IRCondJump):
                    targets.add(instr.then_target)
                    targets.add(instr.else_target)
        return targets
    

    def emit_instr(self, instr):
        if isinstance(instr, IRCall):
            args = ", ".join(self.emit_value(a) for a in instr.args)
            call = f"{instr.callee}({args})"
            if instr.dst is None:
                self.emit(f"{call};")
            else:
                self.emit(f"_t{instr.dst.id} = {call};")
            return
            

        if isinstance(instr, IRReturn):
            if instr.value is None:
                self.emit("return;")
            else:
                self.emit(f"return {self.emit_value(instr.value)};")
            return

        if isinstance(instr, IRBind):
            self.emit(f"{instr.name} = {self.emit_value(instr.value)};")
            return

        if isinstance(instr, IRAssign):
            self.emit(f"{instr.name} = {self.emit_value(instr.value)};")
            return

            
        if isinstance(instr, IRUnOp):
            v = self.emit_value(instr.operand)
            vt = instr.operand.type
            
            if is_vector(vt) and vt == instr.type:
                if instr.op == '-':
                    self.emit(f"_t{instr.dst.id} = "
                              f"lp_{vt[1]}_neg({v});")
                    return
                self.err(f"IR: unary '{instr.op}' on {vt[1]} not supported")
            
            if vt in (('prim', 'q7'), ('prim', 'q15'), ('prim', 'q31')) \
                    and instr.type == vt:
                if instr.op == '-':
                    self.emit(f"_t{instr.dst.id} = "
                              f"lp_{vt[1]}_sub(({self.ctype(vt)})0, {v});")
                    return
                self.err(f"IR: unary '{instr.op}' on {vt[1]} not supported")
            if vt == ('prim', 'bf16') and instr.type == ('prim', 'bf16'):
                self.emit(f"_t{instr.dst.id} = "
                          f"lp_bf16_from_f32(({instr.op}"
                          f"lp_bf16_to_f32({v})));")
                return
            if vt in (('prim', 'bf16'), ('prim', 'q7'),
                      ('prim', 'q15'), ('prim', 'q31')):
                v = self.promote_to_f32(v, vt)
            self.emit(f"_t{instr.dst.id} = ({instr.op}{v});")
            return
            
        if isinstance(instr, IRBinOp):
            a = self.emit_value(instr.left)
            b = self.emit_value(instr.right)
            lt = instr.left.type
            rt = instr.right.type
            dst = instr.type
            
            # Vector result: dispatch to the runtime helper.
            if is_vector(dst):
                opmap = {'+': 'add', '-': 'sub', '*': 'mul', '/': 'div'}
                if instr.op not in opmap:
                    self.err(f"IR: '{instr.op}' not supported on {dst[1]}")
                intrinsic = self.target.intrinsics.get((instr.op, dst[1]))
                if intrinsic:
                    self.emit(f"_t{instr.dst.id} = "
                              f"(({self.ctype(dst)})"
                              f"{{ .v = {intrinsic}({a}.v, {b}.v) }});")
                else:
                    self.emit(f"_t{instr.dst.id} = "
                              f"lp_{dst[1]}_{opmap[instr.op]}({a}, {b});")
                return

            # Quantized result: both operands are the same q type (the
            # lowerer's common_type promotes anything else to f32), so we
            # dispatch to the runtime helper.
            if dst in (('prim', 'q7'), ('prim', 'q15'), ('prim', 'q31')):
                opmap = {'+': 'add', '-': 'sub', '*': 'mul', '/': 'div'}
                if instr.op not in opmap:
                    self.err(f"IR: '{instr.op}' not supported on {dst[1]}")
                self.emit(f"_t{instr.dst.id} = "
                          f"lp_{dst[1]}_{opmap[instr.op]}({a}, {b});")
                return

            # Comparisons: promote q operands to f32 unless both sides
            # are the same q type, in which case raw comparison is exact
            # (q values are 2's-complement and monotonic in value).
            if instr.op in ('==', '!=', '<', '<=', '>', '>='):
                q = ('prim', 'q7'), ('prim', 'q15'), ('prim', 'q31')
                if not (lt == rt and lt in q):
                    a = self.promote_to_f32(a, lt)
                    b = self.promote_to_f32(b, rt)

            # bf16 arithmetic goes through f32 on both paths.
            if dst == ('prim', 'bf16'):
                a_f32 = (a if lt not in (('prim', 'bf16'),
                                         ('prim', 'q7'), ('prim', 'q15'),
                                         ('prim', 'q31'))
                         else self.promote_to_f32(a, lt))
                b_f32 = (b if rt not in (('prim', 'bf16'),
                                         ('prim', 'q7'), ('prim', 'q15'),
                                         ('prim', 'q31'))
                         else self.promote_to_f32(b, rt))
                self.emit(f"_t{instr.dst.id} = "
                          f"lp_bf16_from_f32(({a_f32} {instr.op} {b_f32}));")
                return

            if lt in (('prim', 'bf16'), ('prim', 'q7'),
                      ('prim', 'q15'), ('prim', 'q31')):
                a = self.promote_to_f32(a, lt)
            if rt in (('prim', 'bf16'), ('prim', 'q7'),
                      ('prim', 'q15'), ('prim', 'q31')):
                b = self.promote_to_f32(b, rt)

            self.emit(f"_t{instr.dst.id} = ({a} {instr.op} {b});")
            return
               
        if isinstance(instr, IRStructInit):
            if instr.fields:
                parts = ", ".join(f".{n} = {self.emit_value(v)}"
                                  for n, v in instr.fields)
                body = parts
            else:
                body = "0"
            self.emit(f"_t{instr.dst.id} = "
                      f"(({instr.type[1]}){{ {body} }});")
            return

        if isinstance(instr, IRFieldGet):
            self.emit(f"_t{instr.dst.id} = "
                      f"({self.emit_value(instr.base)}).{instr.field};")
            return
                
        if isinstance(instr, IRVecLit):
            elems = ", ".join(self.emit_value(el) for el in instr.elems)
            self.emit(f"_t{instr.dst.id} = "
                      f"(({self.ctype(instr.type)})"
                      f"{{ .e = {{ {elems} }} }});")
            return

        if isinstance(instr, IRVecIndex):
            self.emit(f"_t{instr.dst.id} = "
                      f"({self.emit_value(instr.vec)}).e"
                      f"[{self.emit_value(instr.index)}];")
            return
                
        if isinstance(instr, IRCast):
            v = self.emit_value(instr.value)
            src = instr.value.type
            dst = instr.type
            q_types = (('prim', 'q7'), ('prim', 'q15'), ('prim', 'q31'))
            src_q = src in q_types
            dst_q = dst in q_types

            if dst_q and not src_q:
                self.emit(f"_t{instr.dst.id} = "
                          f"lp_{dst[1]}_from_f32((float){v});")
                return
            if src_q and not dst_q:
                self.emit(f"_t{instr.dst.id} = "
                          f"(({self.ctype(dst)})lp_{src[1]}_to_f32({v}));")
                return
            if src_q and dst_q and src != dst:
                self.emit(f"_t{instr.dst.id} = "
                          f"lp_{dst[1]}_from_f32(lp_{src[1]}_to_f32({v}));")
                return
            if dst == ('prim', 'bf16') and src != ('prim', 'bf16'):
                self.emit(f"_t{instr.dst.id} = "
                          f"lp_bf16_from_f32((float){v});")
                return
            if src == ('prim', 'bf16') and dst != ('prim', 'bf16'):
                self.emit(f"_t{instr.dst.id} = "
                          f"(({self.ctype(dst)})lp_bf16_to_f32({v}));")
                return
            self.emit(f"_t{instr.dst.id} = "
                      f"(({self.ctype(dst)}){v});")
            return
                   
        if isinstance(instr, IRJump):
            self.emit(f"goto lbl_{instr.target};")
            return

        if isinstance(instr, IRCondJump):
            c = self.emit_value(instr.cond)
            t = instr.cond.type
            if t == ('prim', 'bool'):
                cond_c = c
            elif is_int(t) or t[0] == 'ptr' or t[0] == 'named':
                cond_c = f"({c} != 0)"
            else:
                self.err(f"IR: cannot use '{t}' as a condition")
            self.emit(f"if ({cond_c}) goto lbl_{instr.then_target};")
            self.emit(f"goto lbl_{instr.else_target};")
            return
            
        if isinstance(instr, IRConcat):
            self.emit(f"_t{instr.dst.id} = "
                      f"lp_cat({self.emit_value(instr.left)}, "
                      f"{self.emit_value(instr.right)});")
            return

        if isinstance(instr, IRToString):
            self.emit(f"_t{instr.dst.id} = "
                      f"{self.emit_to_string(instr.value, instr.src_type)};")
            return

        self.err(f"IR: unsupported instruction {type(instr).__name__}")

    # -- operands ------------------------------------------------------------
    def emit_value(self, v):
        if isinstance(v, IRConst):
            return self.emit_const(v)
        if isinstance(v, IRLocal):
            return v.name
        if isinstance(v, IRTemp):
            return f"_t{v.id}"
        self.err(f"IR: unsupported value {v!r}")

    def emit_const(self, v):
        if v.type and v.type[0] == 'named':
            # Enum constant: value is the C identifier, emitted verbatim.
            return str(v.value)
        t = v.type[1] if v.type and v.type[0] == 'prim' else None
        if t == 'str':
            return f"({c_string(v.value)})"
        if t == 'bool':
            return 'true' if v.value else 'false'
        if t == 'char':
            return str(v.value)
        if t == 'f16':
            # Wrap in an explicit cast so the compiler truncates to f16
            # precision rather than inferring from the literal.
            return f"((lp_f16){repr(v.value)})"
        if t in ('f32', 'f64'):
            return repr(v.value)
        return str(v.value)
        
    def emit_to_string(self, value, t):
        c = self.emit_value(value)
        if t == ('prim', 'bool'):
            return f"lp_str_bool({c})"
        if t == ('prim', 'char'):
            return f"lp_str_char({c})"
        if t in (('prim', 'q7'), ('prim', 'q15'), ('prim', 'q31')):
            return f"lp_str_f64((double)lp_{t[1]}_to_f32({c}))"
        if t == ('prim', 'bf16'):
            return f"lp_str_f64((double)lp_bf16_to_f32({c}))"
        if t in (('prim', 'f16'), ('prim', 'f32'), ('prim', 'f64')):
            return f"lp_str_f64((double)({c}))"
        if t[0] == 'ptr':
            return f"lp_str_u64((uint64_t)(uintptr_t)({c}))"
        if is_int(t):
            if t[1].startswith('u'):
                return f"lp_str_u64((uint64_t)({c}))"
            return f"lp_str_i64((int64_t)({c}))"
        self.err(f"IR: cannot stringify type {t}")
        
    def promote_to_f32(self, c, t):
        """Return a C expression that yields c as a float-compatible value."""
        if t in (('prim', 'f16'), ('prim', 'f32'), ('prim', 'f64')):
            return c
        if t == ('prim', 'bf16'):
            return f"lp_bf16_to_f32({c})"
        if t in (('prim', 'q7'), ('prim', 'q15'), ('prim', 'q31')):
            return f"lp_{t[1]}_to_f32({c})"
        return c


def compile_ir(module, fname, freestanding=False, target=None):
    return CEmitter(module, fname, freestanding, target).compile()


def compile_source_ir(src, fname, freestanding=False, search_paths=None,
                      target=None):
    """Full pipeline: source -> AST -> IR -> C. Mirrors compile_source()."""
    from leptonc import lex, Parser, flatten_imports
    from lepton_lower import lower_module

    toks = lex(src, fname)
    items = Parser(toks, fname).parse_program()
    if search_paths is not None:
        items = flatten_imports(items, fname, search_paths)
    module = lower_module(items, fname)
    return compile_ir(module, fname, freestanding, target)
