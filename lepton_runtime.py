PREAMBLE_VEC_OPS = r'''
/* Elementwise vector arithmetic, scalar fallback. GCC/Clang at -O2 turn
   these loops into SIMD when the target supports it, so this is the
   portable baseline. Per-target intrinsics replace this later. */
#define LP_VEC_OPS(NAME, TYPE, COUNT)                                         \
  static inline TYPE lp_##NAME##_add(TYPE a, TYPE b) {                        \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = a.e[i] + b.e[i];         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_sub(TYPE a, TYPE b) {                        \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = a.e[i] - b.e[i];         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_mul(TYPE a, TYPE b) {                        \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = a.e[i] * b.e[i];         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_div(TYPE a, TYPE b) {                        \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = a.e[i] / b.e[i];         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_neg(TYPE a) {                                \
    TYPE r; for (int i = 0; i < COUNT; i++) r.e[i] = -a.e[i];                 \
    return r;                                                                 \
  }

LP_VEC_OPS(v2f64, lp_v2f64,  2)
LP_VEC_OPS(v4f32, lp_v4f32,  4)
LP_VEC_OPS(v4i32, lp_v4i32,  4)
LP_VEC_OPS(v8i16, lp_v8i16,  8)
LP_VEC_OPS(v16i8, lp_v16i8, 16)
#undef LP_VEC_OPS

/* Whole-vector equality for aggregate comparison helpers. NaN lanes
   compare unequal, matching scalar float semantics. */
#define LP_VEC_EQ(NAME, TYPE, COUNT)                                          \
  static inline bool lp_##NAME##_eq(TYPE a, TYPE b) {                         \
    for (int i = 0; i < COUNT; i++) if (a.e[i] != b.e[i]) return false;        \
    return true;                                                              \
  }

LP_VEC_EQ(v2f64, lp_v2f64,  2)
LP_VEC_EQ(v4f32, lp_v4f32,  4)
LP_VEC_EQ(v4i32, lp_v4i32,  4)
LP_VEC_EQ(v8i16, lp_v8i16,  8)
LP_VEC_EQ(v16i8, lp_v16i8, 16)
#undef LP_VEC_EQ

/* Vector reductions. These collapse a vector to a single element of its
   element type. SSE2 has no horizontal-add instruction; AVX2 does. The
   element loop is what GCC and Clang vectorize when they can. */
#define LP_VEC_REDUCE(NAME, TYPE, ETYPE, COUNT)                               \
  static inline ETYPE lp_##NAME##_sum(TYPE a) {                               \
    ETYPE r = a.e[0];                                                         \
    for (int i = 1; i < COUNT; i++) r += a.e[i];                              \
    return r;                                                                 \
  }                                                                           \
  static inline ETYPE lp_##NAME##_max(TYPE a) {                               \
    ETYPE r = a.e[0];                                                         \
    for (int i = 1; i < COUNT; i++) if (a.e[i] > r) r = a.e[i];               \
    return r;                                                                 \
  }                                                                           \
  static inline ETYPE lp_##NAME##_min(TYPE a) {                               \
    ETYPE r = a.e[0];                                                         \
    for (int i = 1; i < COUNT; i++) if (a.e[i] < r) r = a.e[i];               \
    return r;                                                                 \
  }

LP_VEC_REDUCE(v2f64, lp_v2f64,  double,   2)
LP_VEC_REDUCE(v4f32, lp_v4f32,  float,    4)
LP_VEC_REDUCE(v4i32, lp_v4i32,  int32_t,  4)
LP_VEC_REDUCE(v8i16, lp_v8i16,  int16_t,  8)
LP_VEC_REDUCE(v16i8, lp_v16i8,  int8_t,  16)
#undef LP_VEC_REDUCE

/* Broadcast a scalar to every lane. SSE2 uses _mm_set1_*, this is the
   scalar fallback. */
#define LP_VEC_SPLAT(NAME, TYPE, ETYPE, COUNT)                                \
  static inline TYPE lp_##NAME##_splat(ETYPE s) {                             \
    TYPE r;                                                                   \
    for (int i = 0; i < COUNT; i++) r.e[i] = s;                               \
    return r;                                                                 \
  }

LP_VEC_SPLAT(v2f64, lp_v2f64, double,   2)
LP_VEC_SPLAT(v4f32, lp_v4f32, float,    4)
LP_VEC_SPLAT(v4i32, lp_v4i32, int32_t,  4)
LP_VEC_SPLAT(v8i16, lp_v8i16, int16_t,  8)
LP_VEC_SPLAT(v16i8, lp_v16i8, int8_t,  16)
#undef LP_VEC_SPLAT

/* Elementwise vector min/max, comparison masks, and lane select.

   Comparison results use the SSE2 convention: each lane is a bit
   pattern of all 1s (true) or all 0s (false). Users treat the result
   opaquely and pass it to vselect. This matches what _mm_cmplt_ps
   and friends produce, so the x86_64 target's intrinsic path and the
   scalar fallback are bit-identical.

   No SSE2 instruction does a full select, so vselect stays on the
   scalar path even on x86_64. GCC vectorizes it well. */
#define LP_VEC_BINOPS(NAME, TYPE, ETYPE, UTYPE, COUNT)                        \
  static inline TYPE lp_##NAME##_vmax2(TYPE a, TYPE b) {                      \
    TYPE r; for (int i = 0; i < COUNT; i++)                                   \
      r.e[i] = a.e[i] > b.e[i] ? a.e[i] : b.e[i];                             \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_vmin2(TYPE a, TYPE b) {                      \
    TYPE r; for (int i = 0; i < COUNT; i++)                                   \
      r.e[i] = a.e[i] < b.e[i] ? a.e[i] : b.e[i];                             \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_vcmpeq(TYPE a, TYPE b) {                     \
    TYPE r; for (int i = 0; i < COUNT; i++) {                                 \
      union { ETYPE v; UTYPE u; } m;                                          \
      m.u = (a.e[i] == b.e[i]) ? (UTYPE)~(UTYPE)0 : (UTYPE)0;                 \
      r.e[i] = m.v;                                                           \
    }                                                                         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_vcmpne(TYPE a, TYPE b) {                     \
    TYPE r; for (int i = 0; i < COUNT; i++) {                                 \
      union { ETYPE v; UTYPE u; } m;                                          \
      m.u = (a.e[i] != b.e[i]) ? (UTYPE)~(UTYPE)0 : (UTYPE)0;                 \
      r.e[i] = m.v;                                                           \
    }                                                                         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_vcmplt(TYPE a, TYPE b) {                     \
    TYPE r; for (int i = 0; i < COUNT; i++) {                                 \
      union { ETYPE v; UTYPE u; } m;                                          \
      m.u = (a.e[i] < b.e[i]) ? (UTYPE)~(UTYPE)0 : (UTYPE)0;                  \
      r.e[i] = m.v;                                                           \
    }                                                                         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_vcmple(TYPE a, TYPE b) {                     \
    TYPE r; for (int i = 0; i < COUNT; i++) {                                 \
      union { ETYPE v; UTYPE u; } m;                                          \
      m.u = (a.e[i] <= b.e[i]) ? (UTYPE)~(UTYPE)0 : (UTYPE)0;                 \
      r.e[i] = m.v;                                                           \
    }                                                                         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_vcmpgt(TYPE a, TYPE b) {                     \
    TYPE r; for (int i = 0; i < COUNT; i++) {                                 \
      union { ETYPE v; UTYPE u; } m;                                          \
      m.u = (a.e[i] > b.e[i]) ? (UTYPE)~(UTYPE)0 : (UTYPE)0;                  \
      r.e[i] = m.v;                                                           \
    }                                                                         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_vcmpge(TYPE a, TYPE b) {                     \
    TYPE r; for (int i = 0; i < COUNT; i++) {                                 \
      union { ETYPE v; UTYPE u; } m;                                          \
      m.u = (a.e[i] >= b.e[i]) ? (UTYPE)~(UTYPE)0 : (UTYPE)0;                 \
      r.e[i] = m.v;                                                           \
    }                                                                         \
    return r;                                                                 \
  }                                                                           \
  static inline TYPE lp_##NAME##_vselect(TYPE mask, TYPE a, TYPE b) {         \
    TYPE r; for (int i = 0; i < COUNT; i++) {                                 \
      union { ETYPE v; UTYPE u; } m, x, y, z;                                 \
      m.v = mask.e[i]; x.v = a.e[i]; y.v = b.e[i];                            \
      z.u = (x.u & m.u) | (y.u & ~m.u);                                       \
      r.e[i] = z.v;                                                           \
    }                                                                         \
    return r;                                                                 \
  }

LP_VEC_BINOPS(v2f64, lp_v2f64, double,  uint64_t, 2)
LP_VEC_BINOPS(v4f32, lp_v4f32, float,   uint32_t, 4)
LP_VEC_BINOPS(v4i32, lp_v4i32, int32_t, uint32_t, 4)
LP_VEC_BINOPS(v8i16, lp_v8i16, int16_t, uint16_t, 8)
LP_VEC_BINOPS(v16i8, lp_v16i8, int8_t,  uint8_t, 16)
#undef LP_VEC_BINOPS
'''


