"""
Lepton C runtime strings.

This module contains every piece of C that the compiler emits verbatim
into the generated translation unit. It is split into several constants
so that the emitter can pick which ones to include for a given mode:

    PREAMBLE_HEAD        always
    PREAMBLE_READ_HELPERS always
    target.vector_typedefs (from lepton_target.py)
    PREAMBLE_VEC_OPS     always
    RUNTIME              hosted mode only (malloc, write, printf)
    FREESTANDING_DECLS   freestanding mode only (prototypes)
    RUNTIME_MATH         always (self-contained, no libc)

`make_preamble(target)` assembles the always-included portion. The
emitter emits RUNTIME or FREESTANDING_DECLS next, then RUNTIME_MATH.
"""

# =============================================================================
#  Preamble: types, macros, and the fixed-point / half-float typedefs
# =============================================================================

PREAMBLE_HEAD = r'''/* Generated by leptonc. Do not edit by hand. */
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

#if defined(__GNUC__) || defined(__clang__)
#  define LP_UNUSED __attribute__((unused))
#else
#  define LP_UNUSED
#endif

/* f16: native _Float16 when the compiler provides it, else a label over
   float. The fallback is not true half-precision; it exists so programs
   compile on older toolchains while numeric work lands in stages. */
/* On 32-bit x86, native f16/bf16 support requires SSE2; newer GCC
   advertises the type even without the ISA flag. */
#if defined(__FLT16_MANT_DIG__) && (!defined(__i386__) || defined(__SSE2__))
typedef _Float16 lp_f16;
#else
typedef float    lp_f16;
#endif

/* bf16: native __bf16 when available, else a 16-bit container holding the
   top half of an f32. The fallback conversion is a shift and a union
   reinterpret, which is what makes bf16 cheap on hardware without native
   support. Rounding is truncation; round-to-nearest-even is a follow-up. */
#if defined(__BFLT16_MANT_DIG__) && (!defined(__i386__) || defined(__SSE2__))
typedef __bf16 lp_bf16;
static inline float   lp_bf16_to_f32  (lp_bf16 x) { return (float)x; }
static inline lp_bf16 lp_bf16_from_f32(float   x) { return (lp_bf16)x; }
#else
typedef uint16_t lp_bf16;
typedef union { float f; uint32_t u; } lp_bf16_bits;
static inline float lp_bf16_to_f32(lp_bf16 x) {
    lp_bf16_bits b;
    b.u = ((uint32_t)x) << 16;
    return b.f;
}
static inline lp_bf16 lp_bf16_from_f32(float x) {
    lp_bf16_bits b;
    b.f = x;
    return (lp_bf16)(b.u >> 16);
}
#endif

/* Fixed-point types. Each is a signed integer holding `raw / 2^FRAC` of
   the real value. Arithmetic widens to a larger integer, applies
   saturation, and narrows back. This is the representation used by
   quantized inference on hardware without an FPU. */
#define LP_QDEFINE(NAME, TYPE, WIDE, FRAC)                                    \
  typedef TYPE lp_##NAME;                                                     \
  static inline float lp_##NAME##_to_f32(lp_##NAME x) {                       \
    return (float)x / (float)((WIDE)1 << (FRAC));                             \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_from_f32(float x) {                     \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (x >= 1.0f) return (lp_##NAME)maxv;                                    \
    if (x <= -1.0f) return (lp_##NAME)minv;                                   \
    float scaled = x * (float)((WIDE)1 << (FRAC));                            \
    WIDE v = (WIDE)(scaled + (scaled >= 0.0f ? 0.5f : -0.5f));                \
    if (v > maxv) return (lp_##NAME)maxv;                                     \
    if (v < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)v;                                                      \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_add(lp_##NAME a, lp_##NAME b) {         \
    WIDE s = (WIDE)a + (WIDE)b;                                               \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (s > maxv) return (lp_##NAME)maxv;                                     \
    if (s < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)s;                                                      \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_sub(lp_##NAME a, lp_##NAME b) {         \
    WIDE s = (WIDE)a - (WIDE)b;                                               \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (s > maxv) return (lp_##NAME)maxv;                                     \
    if (s < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)s;                                                      \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_mul(lp_##NAME a, lp_##NAME b) {         \
    WIDE p = (WIDE)a * (WIDE)b;                                               \
    p += (WIDE)1 << (FRAC - 1);                                               \
    p >>= FRAC;                                                               \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (p > maxv) return (lp_##NAME)maxv;                                     \
    if (p < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)p;                                                      \
  }                                                                           \
  static inline lp_##NAME lp_##NAME##_div(lp_##NAME a, lp_##NAME b) {         \
    if (b == 0) return (lp_##NAME)(((WIDE)1 << (FRAC)) - 1);                  \
    WIDE q = ((WIDE)a << FRAC) / (WIDE)b;                                     \
    WIDE maxv = ((WIDE)1 << (FRAC)) - 1;                                      \
    WIDE minv = -((WIDE)1 << (FRAC));                                         \
    if (q > maxv) return (lp_##NAME)maxv;                                     \
    if (q < minv) return (lp_##NAME)minv;                                     \
    return (lp_##NAME)q;                                                      \
  }

LP_QDEFINE(q7,  int8_t,  int16_t,  7)
LP_QDEFINE(q15, int16_t, int32_t, 15)
LP_QDEFINE(q31, int32_t, int64_t, 31)
#undef LP_QDEFINE

/* Vector typedefs are target-specific; emitted by make_preamble(). */
'''


