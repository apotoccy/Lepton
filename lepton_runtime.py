PREAMBLE_READ_HELPERS = r'''

/* Little-endian byte readers. Any pointer is treated as raw bytes;
   offsets are in bytes. Unaligned-safe on every target because each
   byte is loaded individually. Available in freestanding mode because
   these are emitted as part of the preamble, not the hosted runtime. */
static LP_UNUSED uint8_t lp_rd_u8(const void *b, int64_t o) {
    return ((const uint8_t*)b)[o];
}
static LP_UNUSED uint16_t lp_rd_u16_le(const void *b, int64_t o) {
    const uint8_t *p = (const uint8_t*)b + o;
    return (uint16_t)((uint16_t)p[0] | ((uint16_t)p[1] << 8));
}
static LP_UNUSED uint32_t lp_rd_u32_le(const void *b, int64_t o) {
    const uint8_t *p = (const uint8_t*)b + o;
    return ((uint32_t)p[0])       | ((uint32_t)p[1] << 8)
         | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}
static LP_UNUSED uint64_t lp_rd_u64_le(const void *b, int64_t o) {
    uint64_t lo = lp_rd_u32_le(b, o);
    uint64_t hi = lp_rd_u32_le(b, o + 4);
    return lo | (hi << 32);
}
static LP_UNUSED int32_t lp_rd_i32_le(const void *b, int64_t o) {
    return (int32_t)lp_rd_u32_le(b, o);
}
static LP_UNUSED int8_t lp_rd_i8_le(const void *b, int64_t o) {
    return (int8_t)((const uint8_t*)b)[o];
}
static LP_UNUSED float lp_rd_f16_le(const void *b, int64_t o) {
    uint16_t h = lp_rd_u16_le(b, o);
    uint32_t sign = (uint32_t)(h & 0x8000u) << 16;
    int      exp  = (int)((h >> 10) & 0x1Fu);
    uint32_t mant = (uint32_t)(h & 0x03FFu);
    uint32_t bits;
    if (exp == 0) {
        if (mant == 0) {
            bits = sign;
        } else {
            /* Subnormal: normalize by shifting mantissa left. */
            int e = -14;
            while ((mant & 0x0400u) == 0) { mant <<= 1; e--; }
            mant &= 0x03FFu;
            bits = sign | ((uint32_t)(e + 127) << 23) | (mant << 13);
        }
    } else if (exp == 31) {
        bits = sign | 0x7F800000u | (mant << 13);  /* inf or nan */
    } else {
        bits = sign | ((uint32_t)(exp + 127 - 15) << 23) | (mant << 13);
    }
    union { uint32_t u; float f; } x;
    x.u = bits;
    return x.f;
}
static LP_UNUSED int64_t lp_rd_i64_le(const void *b, int64_t o) {
    return (int64_t)lp_rd_u64_le(b, o);
}
static LP_UNUSED float lp_rd_f32_le(const void *b, int64_t o) {
    union { uint32_t u; float f; } x;
    x.u = lp_rd_u32_le(b, o);
    return x.f;
}
'''


